def name_fs(name):
    """与现有 19 张同一条规则：名字那一行宽度预算 ≈105px，上限 31px。
    实测：2 字 31、3 字 31、4 字 26、5 字 21、6 字 17。"""
    return min(31, 105 // len(name))


def face_svg(name, art, mark):
    n = len(name)
    ls = '.03em' if n < 4 else '0'
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" width="%d" height="%d" viewBox="0 0 %d %d">'
        '<rect width="%d" height="%d" fill="#ffffff"/>'
        '<rect x="64" y="13" width="22" height="2.4" rx="1.2" fill="%s"/>'
        '<g transform="translate(38,68) scale(3.08)" fill="none">%s</g>'
        '<text x="75" y="206" text-anchor="middle" font-family="%s" font-size="%d" '
        'font-weight="600" fill="%s" letter-spacing="%s">%s</text></svg>'
        % (W, H, W, H, W, H, mark, art, SERIF, name_fs(name), NAME_FILL, ls, name)
    )


def data_uri(name, art, mark):
    return ('data:image/svg+xml;base64,'
            + base64.b64encode(face_svg(name, art, mark).encode('utf-8')).decode('ascii'))


def main():
    with open(DECK, encoding='utf-8') as f:
        deck = json.load(f)
    cards = deck['cards']

    added, updated = [], []
    for spec in CARDS:
        card = {
            'name': spec['name'],
            'keyword': '',
            'symbol': None,
            'sym': None,
            'faceText': '',
            'meaning': spec['meaning'],
            'color': spec['color'],
            'art': None,
            'band': '',
            'image': data_uri(spec['name'], spec['art'], spec['mark']),
            'styleKey': 'aegis',   # ★ 与现有那张一致：名字/关键词交给 CSS 藏掉，牌面只有整面图
        }
        hit = [i for i, c in enumerate(cards) if c.get('name') == spec['name']]
        if hit:
            i = hit[0]
            if all(cards[i].get(k) == v for k, v in card.items()) and set(cards[i]) == set(card):
                print('  = %s 已是最新（第 %d 张）' % (spec['name'], i + 1))
                continue
            cards[i] = card
            updated.append(spec['name'])
        else:
            cards.append(card)
            added.append(spec['name'])

    note_changed = False
    for note in (NOTE_218, NOTE_219, NOTE_220, NOTE_222):
        key = note[2:22]
        if key not in deck['note']:
            deck['note'] = deck['note'].rstrip() + note
            note_changed = True

    with open(DECK, 'w', encoding='utf-8') as f:
        f.write(json.dumps(deck, indent=2, ensure_ascii=False))

    print('Aegis：%s；note %s → 现 %d 张'
          % ('新增 ' + '／'.join(added) if added else ('更新 ' + '／'.join(updated) if updated else '无改动'),
             '已更新' if note_changed else '未变', len(cards)))
    for c in cards:
        print('  %-7s 色 %-3s 牌名字号 %d' % (c['name'], c['color'], name_fs(c['name'])))


if __name__ == '__main__':
    main()
